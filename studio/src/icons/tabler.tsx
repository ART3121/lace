import type { IconProps } from './types';

function tb(Glyph: TablerIcon): ComponentType<IconProps> {
  return function TablerGlyph({ size = 24, strokeWidth = 2, className, style }: IconProps) {
    return <Glyph size={size} stroke={strokeWidth} className={className} style={style} aria-hidden="true" />;
  };
}

