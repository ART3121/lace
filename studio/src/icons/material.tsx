import type { IconName } from './lucide';
import type { IconProps } from './types';

function ms(svg: string, flip = false): ComponentType<IconProps> {
  const d = /\sd="([^"]+)"/.exec(svg)?.[1] ?? '';
  return function MaterialGlyph({ size = 24, className, style }: IconProps) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 -960 960 960"
        width={size}
        height={size}
        fill="currentColor"
        className={className}
        style={flip ? { ...style, transform: 'scaleX(-1)' } : style}
        aria-hidden="true"
      >
        <path d={d} />
      </svg>
    );
  };
}

