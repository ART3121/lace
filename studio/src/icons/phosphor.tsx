import type { IconName } from './lucide';
import type { IconProps } from './types';

function ph(Glyph: PhosphorIcon, weight: IconWeight = 'regular', flip = false): ComponentType<IconProps> {
  return function PhosphorGlyph({ size = 24, className, style }: IconProps) {
    return (
      <Glyph
        size={size}
        weight={weight}
        className={className}
        style={flip ? { ...style, transform: 'scaleX(-1)' } : style}
        aria-hidden="true"
      />
    );
  };
}

